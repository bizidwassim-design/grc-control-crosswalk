#!/usr/bin/env python3
"""Write data/crosswalk.js for the web explorer from the validated sources (same loader as the build).

Usage:  python scripts/build_web_data.py
Generated file; CI fails if it drifts from data/crosswalk.csv and data/overlays/*.csv.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from build_crosswalk import FRAMEWORKS  # noqa: E402
from validate_crosswalk import OVERLAYS, load_all, split_list  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
rows, overlays = load_all()

controls = []
for r in rows:
    c = {k: (r.get(k) or "").strip() for k in ["domain", "iso27001_2022", "iso27001_title", "notes"]}
    for key in FRAMEWORKS:
        if key != "iso27001_2022":
            c[key] = (r.get(key) or "").strip()
    c["overlays"] = {key: [] for key in OVERLAYS}
    controls.append(c)
by_iso = {c["iso27001_2022"]: c for c in controls}

items = {}
for key, meta in OVERLAYS.items():
    out = []
    for it in overlays[key]:
        iso = split_list(it.get("iso27001_2022", ""))
        rec = {
            "ref": it["ref"].strip(), "title": it.get("title", "").strip(), "group": it.get("group", "").strip(),
            "iso27001_2022": iso, "iso27001_clauses": split_list(it.get("iso27001_clauses", "")),
            "confidence": it.get("confidence", "").strip(), "verification": it.get("verification", "").strip(),
            "notes": it.get("notes", "").strip(),
        }
        for extra in meta.get("extra", []):
            rec[extra] = it.get(extra, "").strip()
        out.append(rec)
        for ref in iso:
            if ref in by_iso:
                by_iso[ref]["overlays"][key].append(rec["ref"])
    items[key] = out

data = {
    "frameworks": {k: {"name": v[0], "edition": v[1], "header": v[2]} for k, v in FRAMEWORKS.items()},
    "overlays": {k: {"name": v["name"], "edition": v["edition"], "label": v["label"], "granularity": v["granularity"], "extra": v.get("extra", [])} for k, v in OVERLAYS.items()},
    "controls": controls,
    "overlayItems": items,
}
out = ROOT / "data" / "crosswalk.js"
out.write_text("/* Generated by scripts/build_web_data.py from data/crosswalk.csv and data/overlays/*.csv. Do not edit. MIT License. */\n"
               "window.CROSSWALK = " + json.dumps(data, ensure_ascii=False, indent=1) + ";\n", encoding="utf-8", newline="\n")
print(f"Wrote {out}: {len(controls)} controls, {sum(len(v) for v in items.values())} overlay items in {len(items)} overlays")
